// The web client's route table (app/web/src/api/routes.generated.ts), generated from the
// gateway's public routes: for each route a browser may call, its method, its full path and
// whether its call is keyed, and a type-only import of its definition, which types the call.
// Only types cross into the client, so no server code reaches the browser. Webhook routes (a
// provider's server) and API client routes (a customer's server) are left out.
//
// Usage: node src/scripts/webRoutes.script.ts          writes the file
//        node src/scripts/webRoutes.script.ts --check  fails if the file is not current

import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import type { PublicRoute } from '../contracts/gateway/publicRoute.contract.ts';
import { PUBLIC_ROUTES } from '../contracts/gateway/routeTable.contract.ts';

const SERVER_DIR = path.resolve(import.meta.dirname, '../..');
const GATEWAY_DIR = path.join(SERVER_DIR, 'src/contracts/gateway');
export const WEB_ROUTES_FILE = path.resolve(SERVER_DIR, '../web/src/api/routes.generated.ts');

/**
 * Who may call the route, as the client needs it to offer or disable a control before it is
 * used: the permission the gateway checks, the person's own records, a rule its service decides,
 * or no session at all. The gateway still decides every request.
 */
function accessOf(route: PublicRoute): string {
  if (route.permission !== undefined) return `{ permission: '${route.permission.permission}' }`;
  if (route.ownRecords) return `'own'`;
  if (route.decidedByService !== undefined) return `'service'`;
  return `'open'`;
}

/** The file's text: deterministic, so a check compares it byte for byte. */
export async function webRoutes(): Promise<string> {
  const browser = new Set(PUBLIC_ROUTES.filter((r) => r.webhook === undefined && !r.apiClient));
  const found = new Map<PublicRoute, { file: string; exported: string }>();
  const files = (await readdir(GATEWAY_DIR)).filter((f) => f.endsWith('.contract.ts')).sort();
  for (const file of files) {
    const module = await import(pathToFileURL(path.join(GATEWAY_DIR, file)).href) as Record<string, unknown>;
    for (const [exported, value] of Object.entries(module).sort(([a], [b]) => a.localeCompare(b))) {
      const route = value as PublicRoute;
      if (browser.has(route) && !found.has(route)) found.set(route, { file, exported });
    }
  }
  const missing = [...browser].filter((r) => !found.has(r)).map((r) => r.name);
  if (missing.length > 0) throw new Error(`public routes not exported by name from a gateway contract file: ${missing.join(', ')}`);

  const routes = [...found.entries()].sort(([a], [b]) => a.name.localeCompare(b.name));
  const modules = [...new Set(routes.map(([, at]) => at.file))].sort();
  const alias = new Map(modules.map((file, i) => [file, `m${i}`]));
  const lines = [
    '// Generated by app/server: node src/scripts/webRoutes.script.ts. Do not edit; regenerate when',
    '// a public route changes (the web tests fail until it is current).',
    '',
    // Written as parts: the line is the web client's import, not this script's.
    ...modules.map((file) => ['import type * as', alias.get(file), 'from', `'../../../server/src/contracts/gateway/${file}';`].join(' ')),
    '',
    'export const ROUTES = {',
    ...routes.map(([route]) => `  ${route.name}: { method: '${route.method}', path: '${route.path}', keyed: ${route.forwards?.idempotency === 'keyed'}, `
      + `session: '${route.session}', access: ${accessOf(route)}, writes: ${route.writes} },`),
    '} as const;',
    '',
    'export interface Routes {',
    ...routes.map(([route, at]) => `  ${route.name}: typeof ${alias.get(at.file)}.${at.exported};`),
    '}',
    '',
  ];
  return lines.join('\n');
}

if (process.argv[1] !== undefined && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = await webRoutes();
  if (process.argv.includes('--check')) {
    const current = await readFile(WEB_ROUTES_FILE, 'utf8').catch(() => '');
    if (current !== text) {
      process.stderr.write(`${path.relative(process.cwd(), WEB_ROUTES_FILE)} is not current: run node src/scripts/webRoutes.script.ts in app/server\n`);
      process.exit(1);
    }
  } else {
    await writeFile(WEB_ROUTES_FILE, text);
    process.stdout.write(`wrote ${path.relative(process.cwd(), WEB_ROUTES_FILE)}\n`);
  }
}
