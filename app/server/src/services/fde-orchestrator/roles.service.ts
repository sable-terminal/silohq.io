/** Weekly, Monday 08:00 in the organisation's time zone: well above any plan's minimum interval. */
export const CRON_NOTIFY_SCHEDULE = '0 8 * * 1';

async function proposeCrons(r: RoleContext): Promise<TaskOutcome> {
  const manifest = await r.deps.services.call(getManifest, { query: {} }, as(r));
  const boards = await read(r, async (db) => {
    const accepted = (await fdeProposalRepo.listForEngagement(db, r.e.id, { kind: 'dashboard' }))
      .filter((p) => p.status === 'accepted' || p.status === 'accepted_edited');
    const targets = await fdeProposalTargetRepo.appliedFor(db, accepted.map((p) => p.id));
    return accepted.flatMap((p) => {
      const savedViewId = targets.find((t) => t.proposalId === p.id)?.savedViewId;
      const payload = p.payload as { objectTypeId: string; name: string };
      return savedViewId == null ? [] : [{ savedViewId, objectTypeId: payload.objectTypeId, name: payload.name, decidedBy: p.decidedBy }];
    });
  });
  const proposals: NewProposal[] = [];
  for (const board of boards) {
    if (await already(r, 'cron_notify', 'savedViewId', board.savedViewId)) continue;
    const type = manifest.objectTypes.find((t) => t.id === board.objectTypeId && t.status === 'active');
    if (type === undefined) continue;
    // 51.9: a condition over a halted connection is not proposed.
    const connections = [...new Set(type.contributingObjects.map((c) => c.connectionId))];
    const statuses = await Promise.all(connections.map((connectionId) => r.deps.services.call(getConnection, { params: { connectionId } }, as(r))));
    if (statuses.some((c) => c.status !== 'active')) continue;
    proposals.push({
      kind: 'cron_notify',
      payload: {
        savedViewId: board.savedViewId, objectTypeId: type.id, name: `${board.name}: weekly changes`.slice(0, 200), schedule: CRON_NOTIFY_SCHEDULE,
        condition: { kind: 'result', operator: 'differs_from_previous' }, recipients: [],
      },
      evidence: [{ type: 'documentation', saved_view_id: board.savedViewId, detail: 'over the dashboard view a person accepted in stage 6; notify only, never a mutate action' }],
      confidence: 0.6, verification: { sources_active: connections.length, mode: 'notify' },
      markings: await markingsOf(r, { connections, objectTypes: [type.id] }),
    });
  }
  return { proposals };
}

// ----------------------------------------------------------------------------- stage 9: Reliability

/** What Reliability reads about one connection: structure, counts and codes, never a value. */
export interface ReliabilityInputs {
  connectionId: string;
  connectionStatus: string;
  heals: readonly HealProposalView[];
  /** The latest completed weekly or manual re-check. */
  recheck: RecheckView | undefined;
  stream: StreamStatusView | undefined;
  /** Each field's two latest profiles, newest first per field. */
  profiles: readonly FieldProfileView[];
}

/** A change of this much between a field's last two profiles is reported (51.11). */
export const PROFILE_DRIFT = { nullRate: 0.2, distinctRatio: 0.3, typeConformance: 0.2, rowsFall: 0.5 } as const;
/** Reliability profiles a connection again when its newest profile is older than this. */
export const PROFILE_EVERY_MS = 7 * 24 * 3_600_000;

type FieldProfileView = z.infer<typeof fieldProfileView>;
const rate = (n: number, of: number) => (of === 0 ? 0 : Math.round((n / of) * 1000) / 1000);

/** Reliability's proposals for one connection, before markings; deduplication is the task's. */
export function reliabilityProposals(i: ReliabilityInputs): Array<Omit<NewProposal, 'markings'>> {
  const out: Array<Omit<NewProposal, 'markings'>> = [];
  const finding = (finding: string, findingKey: string, detail: Record<string, unknown>, evidence: Evidence[], confidence: number) =>
    out.push({ kind: 'reliability_finding', payload: { connectionId: i.connectionId, finding, findingKey, ...detail }, evidence, confidence,
      verification: { observed: finding } });

  for (const h of i.heals) {
    const drift = h.drift.map((d) => ({ kind: d.kind, object: d.object, field: d.field }));
    const probe: Evidence = { type: 'probe', heal_proposal_id: h.id, detail: `the re-check found ${h.drift.length} drift against the manifest` };
    if (h.disposition === 'awaiting_review') {
      out.push({
        kind: 'heal_review',
        payload: { connectionId: i.connectionId, healProposalId: h.id, changeKind: h.changeKind, changes: h.changes, drift, sandbox: h.sandbox.status },
        evidence: h.sandbox.status === 'passed' && h.sandbox.conformanceRunId !== null
          ? [probe, { type: 'sandbox_cycle', conformance_run_id: h.sandbox.conformanceRunId, detail: 'the repaired version passed conformance in the sandbox' }]
          : [probe],
        confidence: h.sandbox.status === 'passed' ? 0.8 : 0.5,
        verification: { sandbox: h.sandbox.status, change_kind: h.changeKind },
      });
    } else if (h.disposition === 'halted') {
      // A change of meaning, a removed object or a narrowed type halts and is reported (17.3).
      finding('halted', `heal:${h.id}`, { healProposalId: h.id, changeKind: h.changeKind, drift }, [probe], 0.9);
    }
  }

  if (i.recheck !== undefined && i.recheck.verified === false) {
    finding('conformance_failing', `recheck:${i.recheck.id}`,
      { recheckId: i.recheck.id, conformanceRunId: i.recheck.conformanceRunId, errors: i.recheck.errors.slice(0, 20) },
      [{ type: 'probe', recheck_id: i.recheck.id, detail: 'the weekly re-check\'s conformance run did not pass' }], 0.9);
  }

  // A stream silent or behind while the source is otherwise healthy (18.7).
  if (i.connectionStatus === 'active' && i.recheck?.verified !== false) {
    for (const o of i.stream?.objects ?? []) {
      if (o.status !== 'stale' && o.status !== 'delayed') continue;
      const kind = o.status === 'stale' ? 'stream_silent' : 'stream_lagging';
      finding(kind, `${kind}:${o.object}:${o.lastDeltaAt ?? 'never'}`, { object: o.object, source: o.inUse, lastDeltaAt: o.lastDeltaAt, reason: o.reason },
        [{ type: 'probe', detail: `the ${o.inUse} stream for ${o.object} is ${o.status} while the connection is active and its re-check passed` }], 0.7);
    }
  }

  // Profile drift: counts, distinctness, null rates and type conformance between the last two profiles.
  const byField = new Map<string, FieldProfileView[]>();
  for (const p of i.profiles) byField.set(`${p.sourceObject}\u0000${p.fieldPath}`, [...(byField.get(`${p.sourceObject}\u0000${p.fieldPath}`) ?? []), p]);
  for (const [now, before] of [...byField.values()].filter((v) => v.length >= 2).map((v) => [...v].sort((a, b) => b.profiledAt.localeCompare(a.profiledAt)))) {
    const measures = {
      rows: [before!.rowCount, now!.rowCount],
      nullRate: [rate(before!.nullCount + before!.emptyCount, before!.rowCount), rate(now!.nullCount + now!.emptyCount, now!.rowCount)],
      distinctRatio: before!.distinctCount === null || now!.distinctCount === null ? null
        : [rate(before!.distinctCount, before!.rowCount), rate(now!.distinctCount, now!.rowCount)],
      typeConformance: [rate(before!.typeConformanceCount, before!.rowCount), rate(now!.typeConformanceCount, now!.rowCount)],
    };
    const moved = [
      ...(before!.rowCount > 0 && now!.rowCount < before!.rowCount * (1 - PROFILE_DRIFT.rowsFall) ? ['rows'] : []),
      ...(Math.abs(measures.nullRate[1]! - measures.nullRate[0]!) >= PROFILE_DRIFT.nullRate ? ['null_rate'] : []),
      ...(measures.distinctRatio !== null && Math.abs(measures.distinctRatio[1]! - measures.distinctRatio[0]!) >= PROFILE_DRIFT.distinctRatio ? ['distinctness'] : []),
      ...(measures.typeConformance[0]! - measures.typeConformance[1]! >= PROFILE_DRIFT.typeConformance ? ['type_conformance'] : []),
    ];
    if (moved.length === 0) continue;
    finding('profile_drift', `profile:${now!.sourceObject}:${now!.fieldPath}:${now!.profiledAt}`,
      { object: now!.sourceObject, field: now!.fieldPath, moved, measures, profiledAt: [before!.profiledAt, now!.profiledAt] },
      [{ type: 'field_profile', object: now!.sourceObject, field: now!.fieldPath, detail: `${moved.join(', ')} moved between the last two profiles` }],
      moved.includes('type_conformance') || moved.includes('distinctness') ? 0.7 : 0.6);
  }
  return out;
}

async function watchReliability(r: RoleContext): Promise<TaskOutcome> {
  const connectionId = String(refs(r.task)['connectionId']);
  const connection = await r.deps.services.call(getConnection, { params: { connectionId } }, as(r));
  if (connection.status === 'revoked') return { proposals: [] };
  const heals = (await r.deps.services.call(listHealProposals, { query: { connectionId, limit: 50 } }, as(r))).proposals;
  const recheck = (await r.deps.services.call(listRechecks, { params: { connectionId }, query: { limit: 5 } }, as(r))).rechecks
    .find((x) => x.status === 'completed');
  const stream = await r.deps.services.call(getStreamStatus, { params: { connectionId } }, as(r));
  const profilesOf = async () => (await r.deps.services.call(listFieldProfiles, { params: { connectionId }, query: { depth: 2 } }, as(r))).profiles;
  let profiles = await profilesOf();
  const newest = profiles.reduce((at, p) => Math.max(at, Date.parse(p.profiledAt)), 0);
  if (profiles.length > 0 && connection.status === 'active' && newest <= nowOf(r.deps).getTime() - PROFILE_EVERY_MS) {
    // Profiling reads counts only (22.3); a source that cannot be profiled leaves the old profile standing.
    await r.deps.services.call(profileConnection, { params: { connectionId }, body: {} }, as(r));
    profiles = await profilesOf();
  }
  const proposals: NewProposal[] = [];
  for (const p of reliabilityProposals({ connectionId, connectionStatus: connection.status, heals, recheck, stream, profiles })) {
    const key = p.kind === 'heal_review' ? ['healProposalId', String(p.payload['healProposalId'])] : ['findingKey', String(p.payload['findingKey'])];
    if (await already(r, p.kind, key[0]!, key[1]!)) continue;
    proposals.push({ ...p, markings: await markingsOf(r, { connections: [connectionId] }) });
  }
  return { proposals };
}

