/** The stop condition (51.1): which sub-stage failed, and why, as a category. */
export class TaskFailure extends Error {
  readonly semantic: ErrorSemantic;
  readonly subStage: string;
  constructor(semantic: ErrorSemantic, subStage: string, message: string) {
    super(message);
    this.semantic = semantic;
    this.subStage = subStage;
  }
}

