/** The error semantic a build's failing stage stands for (51.4: parse, probe, reconcile are named). */
function buildFailure(stage: string, errors: unknown): ErrorSemantic {
  const codes = JSON.stringify(errors ?? '');
  if (/auth|401|403|credential|secret/.test(codes)) return 'auth';
  if (/unsupported|transport/.test(codes)) return 'unsupported_transport';
  return stage === 'probe' || stage === 'conform' ? 'upstream' : 'schema';
}

/**
 * Stage 2 (51.4): a connector the AI builder is building for a system in scope. The person
 * runs the builder's probe (it moves the connection, runs conformance and versions the
 * manifest: authority the AI FDE never holds); the task waits for it. A build that stops
 * names its stage and stops this system's work. Once mappings are proposed: the manifest
 * (validated, probed, conformance run) and each object's mapping, with its identifier and
 * confidence, go to a person. Accepting a mapping confirms it in the builder as that person,
 * which verifies the connection when they hold connector.verify.
 */
async function buildConnector(r: RoleContext): Promise<TaskOutcome> {
  const connectionId = String(refs(r.task)['connectionId'] ?? r.task.connectionId);
  const build = await r.deps.services.call(getBuild, { params: { connectionId } }, as(r));
  if (build.running) return { wait: true, inputRefs: refs(r.task) };
  if (build.status === 'failed' && build.stage !== 'verify') {
    const failed = [...build.stages].reverse().find((s) => s.status === 'failed')!;
    throw new TaskFailure(buildFailure(failed.stage, failed.errors), failed.stage,
      `the build stopped at ${failed.stage}; it stays a draft the visual builder can open`);
  }
  const done = new Set(build.stages.filter((s) => s.status === 'completed').map((s) => s.stage));
  if (!done.has('propose_mapping')) return { wait: true, inputRefs: refs(r.task) };
  if (build.proposals.length === 0) throw new TaskFailure('not_found', 'propose_mapping', 'the build discovered no object to map');

  const markings = await markingsOf(r, { connections: [connectionId] });
  const stages = build.stages.filter((s) => s.status === 'completed').map((s) => s.stage);
  const proposals: NewProposal[] = [];
  if (!await already(r, 'connector_manifest', 'manifestId', build.manifest.id)) {
    proposals.push({
      kind: 'connector_manifest',
      payload: { connectionId, connectorId: build.connectorId, manifestId: build.manifest.id, version: build.manifest.version,
        objects: build.proposals.map((p) => p.object), conformanceRunId: build.conformanceRunId },
      evidence: [{ type: 'probe', connection_id: connectionId, detail: `the builder completed ${stages.join(', ')}; the probe is the source of truth` }],
      confidence: build.conformanceRunId === null ? 0.6 : 0.8, verification: { stages, conformance_run_id: build.conformanceRunId }, markings,
    });
  }
  for (const p of build.proposals) {
    const mappingKey = `${connectionId}:${p.object}`;
    if (await already(r, 'connector_mapping', 'mappingKey', mappingKey)) continue;
    proposals.push({
      kind: 'connector_mapping',
      payload: { connectionId, mappingKey, object: p.object, objectType: p.objectType, identifier: p.identifier,
        properties: p.properties.map((x) => ({ field: x.field, property: x.property })), links: p.links },
      evidence: [{ type: 'probe', connection_id: connectionId, object: p.object, detail: `${p.object} read whole in the probe; identifier ${p.identifier.join(', ') || 'none found'}` },
        ...p.links.map((l): Evidence => ({ type: 'foreign_key', object: p.object, field: l.field, detail: `${l.field} references ${l.targetObject}.${l.targetField}` }))],
      confidence: p.confidence, verification: { identifier: p.identifier, properties: p.properties.length }, markings,
    });
  }
  return { proposals };
}

/** The error semantic a refused draft stands for (51.4: the parse stage). */
function draftFailure(error: { category: string; code: string }): ErrorSemantic {
  if (error.category === 'forbidden') return 'ceiling';
  if (/unsupported|transport/.test(error.code)) return 'unsupported_transport';
  return error.code === 'build.parse_no_objects' ? 'not_found' : 'schema';
}

/**
 * Stage 2 (51.4) for a system the organisation listed: the Integration principal drafts its
 * connector from the documentation given (the builder's parse, metered to the engagement where
 * a model reads it), as a sandbox connection its owner, the engaging administrator, owns. The
 * credential is theirs to give through the credential path; until a live one is held the task
 * waits (the system shows awaitingCredential). Then the principal probes it, and the build
 * goes on as any other (buildConnector). A draft the builder refuses stops at parse, naming why.
 */
async function draftConnectorFor(r: RoleContext): Promise<TaskOutcome> {
  const systemId = String(refs(r.task)['systemId']);
  let system = await read(r, (db) => fdeEngagementSystemRepo.findById(db, systemId));
  if (system === undefined || system.status === 'withdrawn') return { proposals: [] };
  if (system.connectionId === null) {
    let built;
    try {
      built = await r.deps.services.call(draftConnector, { body: {
        name: system.name, slug: system.slug, provider: system.provider, documentation: documentationOf(system),
        ...(system.baseUrl === null ? {} : { baseUrl: system.baseUrl }),
        sandbox: { name: system.name, owningScopeId: system.owningScopeId, parameters: system.parameters as Record<string, string> },
      } }, as(r, { idempotencyKey: `fde.${r.task.id}.draft` }));
    } catch (error) {
      if (!isAppError(error) || error.category === 'unavailable' || error.category === 'timeout') throw error;
      throw new TaskFailure(draftFailure(error), 'parse', `the documentation could not be drafted (${error.code}); a person can correct it in the visual builder or list the system again`);
    }
    const connectionId = built.connectionId;
    system = await inTransaction(r.deps.databases.pool('control'), { organisationId: r.e.organisationId },
      async (db) => (await fdeEngagementSystemRepo.update(db, systemId, { status: 'drafted', connectionId, draftedAt: nowOf(r.deps).toISOString() }))!);
  }
  const connectionId = system.connectionId!;
  const build = await r.deps.services.call(getBuild, { params: { connectionId } }, as(r));
  if (!build.running && !build.stages.some((s) => s.stage !== 'parse')) {
    // The AI FDE never holds a secret (52.1): the connection's owner gives it; the probe waits for it.
    if (await read(r, (db) => awaitingCredential(db, connectionId))) return { wait: true, inputRefs: refs(r.task) };
    await r.deps.services.call(probeBuild, { params: { connectionId } }, as(r, { idempotencyKey: `fde.${r.task.id}.probe` }));
    return { wait: true, inputRefs: refs(r.task) };
  }
  return buildConnector({ ...r, task: { ...r.task, connectionId, inputRefs: { ...refs(r.task), connectionId } } });
}

