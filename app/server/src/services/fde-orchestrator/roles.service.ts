/** The tasks a stage needs, planned once when it begins (or again on a new attempt). */
export async function planStage(deps: FdeDeps, e: FdeEngagement, stageNumber: number, principals: Partial<Record<FdeRole, string>>)
  : Promise<PlannedTask[]> {
  const scope = await inTransaction(deps.databases.pool('control'), { organisationId: e.organisationId }, (db) => inScope(db, e.id), { readOnly: true });
  const manifestFor = async (role: FdeRole) => principals[role] === undefined ? undefined
    : deps.services.call(getManifest, { query: {} }, { request: asPrincipal(e.organisationId, principals[role]!), correlationId: e.id });
  const inScopeTypes = async (role: FdeRole) => ((await manifestFor(role))?.objectTypes ?? [])
    .filter((t) => t.status === 'active' && t.contributingObjects.some((c) => scope.accepted.includes(c.connectionId)));
  switch (stageNumber) {
    case 1: return [{ role: 'survey', kind: 'survey_estate', inputRefs: {} }];
    case 2: {
      // Integration (51.4): each listed system's connector drafted from its documentation and built; each other system in
      // scope whose connector a person is still building.
      if (principals.integration === undefined || scope.accepted.length + scope.pending.length === 0) return [];
      const systems = await inTransaction(deps.databases.pool('control'), { organisationId: e.organisationId },
        (db) => fdeEngagementSystemRepo.listForEngagement(db, e.id), { readOnly: true });
      const listed = systems.filter((s) => s.status !== 'withdrawn');
      const drafting = new Set(listed.map((s) => s.connectionId).filter((id): id is string => id !== null));
      const { connections } = await deps.services.call(listConnections, { query: { limit: 500 } },
        { request: asPrincipal(e.organisationId, principals.integration), correlationId: e.id });
      const status = new Map(connections.map((c) => [c.id, c.status]));
      return [
        ...listed.filter((s) => s.connectionId === null || status.get(s.connectionId) === 'draft' || status.get(s.connectionId) === 'probing')
          .map((s) => ({ role: 'integration' as const, kind: 'draft_connector', inputRefs: { systemId: s.id } })),
        ...connections.filter((c) => scope.accepted.includes(c.id) && !drafting.has(c.id) && (c.status === 'draft' || c.status === 'probing'))
          .map((c) => ({ role: 'integration' as const, kind: 'build_connector', connectionId: c.id, inputRefs: { connectionId: c.id } })),
      ];
    }
    case 3: return scope.accepted.map((connectionId) => ({ role: 'ontology', kind: 'derive_object_types', connectionId, inputRefs: { connectionId } }));
    case 4: return (await inScopeTypes('ontology'))
      .filter((t) => new Set(t.contributingObjects.map((c) => `${c.connectionId}/${c.sourceObject}`)).size >= 2)
      .map((t) => ({ role: 'ontology', kind: 'propose_resolution', inputRefs: { objectTypeId: t.id } }));
    case 5: return [
      ...scope.accepted.map((connectionId) => ({ role: 'integration' as const, kind: 'propose_write_enablement', connectionId, inputRefs: { connectionId } })),
      ...(await inScopeTypes('action')).map((t) => ({ role: 'action' as const, kind: 'propose_action_types', inputRefs: { objectTypeId: t.id } })),
    ];
    case 6: return (await inScopeTypes('application')).map((t) => ({ role: 'application' as const, kind: 'draft_type_views', inputRefs: { objectTypeId: t.id } }));
    case 7: return [
      ...(await inScopeTypes('application')).map((t) => ({ role: 'application' as const, kind: 'configure_detectors', inputRefs: { objectTypeId: t.id } })),
      { role: 'application', kind: 'propose_crons', inputRefs: {} },
    ];
    case 8: return [{ role: 'simulation', kind: 'propose_edges', inputRefs: {} }];
    case 9: return scope.accepted.map((connectionId) => ({ role: 'reliability' as const, kind: 'watch_reliability', connectionId, inputRefs: { connectionId } }));
    default: return [];
  }
}

