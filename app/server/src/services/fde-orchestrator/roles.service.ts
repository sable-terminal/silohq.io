/** The parameter type each data type is set from; composite types are left to a person. */
const PARAMETER_OF: Partial<Record<string, 'string' | 'integer' | 'decimal' | 'boolean' | 'date' | 'timestamp'>> = {
  string: 'string', enum: 'string', integer: 'integer', decimal: 'decimal', boolean: 'boolean', date: 'date', timestamp: 'timestamp',
};

/** A connection the type is stored on, with the source object it is read from. */
export interface WritableSource {
  connection: { id: string; writesEnabled: boolean };
  protocol: string;
  object: ManifestObject;
}

/**
 * Stage 5 (51.7): an "Update" Action type over the type's properties stored on the
 * connections that have earned writes, write over a transport that writes, and declare an
 * update on the source object. Each property is an optional parameter; a property not given
 * keeps its current value. Each object is written on its own connection. A physical source
 * makes the type physical. Undefined when there is nothing it could write.
 */
export function actionTypeProposalFor(type: ObjectTypeView, sources: readonly WritableSource[], owningScopeId: string,
  ontologyVersionId: string): { payload: Record<string, unknown>; connectionIds: string[]; propertyIds: string[] } | undefined {
  const writable = sources.filter((s) => s.connection.writesEnabled && (WRITING_PROTOCOLS as readonly string[]).includes(s.protocol)
    && s.object.writes?.update !== undefined && s.object.identifier.length === 1);
  const mappedOn = (p: ObjectTypeView['properties'][number]) => writable.some((s) =>
    p.mappings.some((m) => m.connectionId === s.connection.id && m.sourceObject === s.object.name && s.object.fields.some((f) => f.name === m.fieldPath)));
  const properties = type.properties.filter((p) => p.status === 'active' && p.computedFunctionVersionId === null
    && p.identityId !== type.primaryKeyPropertyIdentityId && PARAMETER_OF[p.dataType] !== undefined && mappedOn(p));
  if (properties.length === 0) return undefined;
  const connectionIds = writable.map((s) => s.connection.id);
  return {
    connectionIds, propertyIds: properties.map((p) => p.identityId),
    payload: {
      objectTypeId: type.id, apiName: `update_${type.apiName}`.slice(0, 63), displayName: `Update ${type.displayName}`, owningScopeId,
      definition: {
        ontologyVersionId, objectTypeId: type.id, properties: properties.map((p) => p.apiName),
        parameters: properties.map((p) => ({ name: p.apiName, type: PARAMETER_OF[p.dataType]!, required: false })),
        rules: properties.map((p) => ({
          kind: 'set_property', property: p.apiName, value: { cel: `params.${p.apiName} == null ? current.${p.apiName} : params.${p.apiName}` },
        })),
        permittedConnections: connectionIds, riskClass: writable.some((s) => s.object.writes!.risk === 'physical') ? 'physical' : 'data',
      },
    },
  };
}

async function proposeActionTypes(r: RoleContext): Promise<TaskOutcome> {
  const objectTypeId = String(refs(r.task)['objectTypeId']);
  if (await already(r, 'action_type', 'objectTypeId', objectTypeId)) return { proposals: [] };
  const manifest = await r.deps.services.call(getManifest, { query: {} }, as(r));
  const type = manifest.objectTypes.find((t) => t.id === objectTypeId);
  if (type === undefined) throw new TaskFailure('not_found', 'action_types', 'the type is no longer in the ontology');
  const scope = await read(r, (db) => inScope(db, r.e.id));
  // Write enablement comes first: wait while a source's cycle is being read or its proposal waits on a person.
  const contributing = type.contributingObjects.map((c) => c.connectionId).filter((id) => scope.accepted.includes(id));
  const undecided = await read(r, async (db) => {
    const open = (await fdeTaskRepo.listForStage(db, r.task.stageId)).some((t) => t.kind === 'propose_write_enablement'
      && (t.status === 'queued' || t.status === 'running') && t.connectionId !== null && contributing.includes(t.connectionId));
    if (open) return true;
    for (const id of contributing) if (await fdeProposalRepo.pendingWith(db, r.e.id, 'write_enablement', 'connectionId', id)) return true;
    return false;
  });
  if (undecided) return { wait: true, inputRefs: refs(r.task) };
  const loaded: Array<WritableSource & { name: string; owningScopeId: string }> = [];
  for (const c of type.contributingObjects.filter((x) => scope.accepted.includes(x.connectionId))) {
    const connection = await r.deps.services.call(getConnection, { params: { connectionId: c.connectionId } }, as(r));
    const version = await r.deps.services.call(getManifestVersion, { params: { connectorId: connection.connectorId, versionId: connection.manifestId } }, as(r));
    const document = manifestSchema.safeParse(version.document);
    const object = document.success ? document.data.objects.find((o) => o.name === c.sourceObject) : undefined;
    if (object !== undefined) {
      loaded.push({ connection, protocol: document.data!.protocol.kind, object, name: connection.name, owningScopeId: connection.owningScopeId });
    }
  }
  if (loaded.length === 0) return { proposals: [] };
  const proposal = actionTypeProposalFor(type, loaded, loaded[0]!.owningScopeId, manifest.version.id);
  if (proposal === undefined) return { proposals: [] };
  const named = loaded.filter((s) => proposal.connectionIds.includes(s.connection.id)).map((s) => s.name).join(', ');
  return { proposals: [{
    kind: 'action_type', payload: proposal.payload,
    evidence: proposal.connectionIds.map((id) => ({ type: 'sandbox_cycle', connection_id: id, detail: 'writes earned: the write-verify-undo class passed' })),
    confidence: 0.8, verification: { writes_enabled: named, update_declared: true, properties: proposal.propertyIds.length },
    markings: await markingsOf(r, { connections: proposal.connectionIds, objectTypes: [type.id], properties: proposal.propertyIds }),
  }] };
}

/**
 * Stage 5 (51.7): write enablement for a connection whose manifest declares writes, from the
 * write-verify-undo class run on its current manifest version. The run is a person's: they
 * nominate the test record and its values (connector.verify), which no model invents. A
 * physical source is never cycled by the AI FDE; its safety owner enables it outside the cycle.
 */
export async function writeEnablementFor(connectionId: string, manifest: Manifest, status: () => Promise<WriteClassStatus>)
  : Promise<Omit<NewProposal, 'markings'> | undefined> {
  const written = manifest.objects.filter((o) => o.writes !== undefined
    && (o.writes.create !== undefined || o.writes.update !== undefined || o.writes.delete !== undefined || o.writes.custom.length > 0));
  if (written.length === 0) return undefined;
  if (written.some((o) => o.writes!.risk === 'physical')) return undefined;
  if (!(WRITING_PROTOCOLS as readonly string[]).includes(manifest.protocol.kind)) {
    throw new TaskFailure('unsupported_transport', 'write_class', `the ${manifest.protocol.kind} transport does not write yet: the connector stays read-only`);
  }
  const { manifestId, run } = await status();
  if (run === null) {
    throw new TaskFailure('not_found', 'write_class',
      'no test record has been nominated: run the write-verify-undo class on one to earn writes; until then the connector stays read-only');
  }
  if (!run.passed) {
    throw new TaskFailure('upstream', 'write_class',
      `the write-verify-undo cycle failed (${run.failedCount} tests): it is not proposed for enablement and the connector stays read-only`);
  }
  return {
    kind: 'write_enablement',
    payload: { connectionId, manifestId, conformanceRunId: run.id, objects: written.map((o) => o.name) },
    evidence: [{ type: 'sandbox_cycle', connection_id: connectionId, conformance_run_id: run.id,
      detail: `the write-verify-undo class passed ${run.passedCount} tests on the current manifest version` }],
    confidence: 0.9, verification: { write_class_passed: true, failed: 0, passed: run.passedCount, completed_at: run.completedAt },
  };
}

async function proposeWriteEnablement(r: RoleContext): Promise<TaskOutcome> {
  const connectionId = String(refs(r.task)['connectionId']);
  const connection = await r.deps.services.call(getConnection, { params: { connectionId } }, as(r));
  if (connection.writesEnabled || await already(r, 'write_enablement', 'connectionId', connectionId)) return { proposals: [] };
  const version = await r.deps.services.call(getManifestVersion, { params: { connectorId: connection.connectorId, versionId: connection.manifestId } }, as(r));
  const parsed = manifestSchema.safeParse(version.document);
  if (!parsed.success) throw new TaskFailure('schema', 'write_class', 'the connection runs a manifest that does not read');
  const proposal = await writeEnablementFor(connectionId, parsed.data,
    () => r.deps.services.call(getWriteClassStatus, { params: { connectionId } }, as(r)));
  if (proposal === undefined) return { proposals: [] };
  return { proposals: [{ ...proposal, markings: await markingsOf(r, { connections: [connectionId] }) }] };
}

