//            and a notify-only Cron per dashboard a person accepted in stage 6 (weekly, telling
//            them when the view's objects differ from the last run), never over a halted source
//            and never with a mutate action (50.10); the accepting person owns it
//   stage 8  Simulation: an edge per link type, its kind and lead time left for a person to state
//   stage 9  Reliability, also under a successor engagement after handover: per in-scope
//            connection, a heal awaiting review becomes heal_review; a heal that halted, a
//            failing weekly re-check, a stream gone silent or lagging while the source is
//            otherwise healthy, and a field profile that drifted become reliability_finding.
//            The heal policy is the maintenance service's own: nothing here applies a repair
//            or a new field without a person.
//   stage 6  Application: per in-scope type, a Studio app from a template bound to the type
//            (inbox and detail with its accepted Action type, otherwise a monitor), proposed
//            only when Studio validates it with no finding and it renders for the role; and a
//            custom object view layout (identity apart, the Action button, timeline and Ask),
//            validated the same way; and a dashboard (a saved view over the type's objects,
//            on the person's dashboard). The accepting person owns each; the app and the
//            layout are drafts marked as generated by the AI FDE, published through review.
//   stage 2  Integration: per system the organisation listed, its connector drafted from the
//            documentation given (the builder's parse, as the Integration principal), probed once
//            the connection's owner has given its credential (never seen here), then its manifest
//            and each object's mapping proposed; and a connector a person is building in the
