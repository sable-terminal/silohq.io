/** Stage 7 (51.9): the field each detector needs, chosen from structure only; never a threshold. */
async function configureDetectors(r: RoleContext): Promise<TaskOutcome> {
  const objectTypeId = String(refs(r.task)['objectTypeId']);
  const manifest = await r.deps.services.call(getManifest, { query: {} }, as(r));
  // The model is told only what the engagement's principals see (49.5).
  const type = manifest.objectTypes.find((t) => t.id === objectTypeId);
  if (type === undefined) return { proposals: [] };
  const { detectors } = await r.deps.services.call(listDetectors, {}, as(r));
  const { configurations } = await r.deps.services.call(listConfigurations, { params: { objectTypeId } }, as(r));
  const configured = new Set(configurations.map((c) => c.detector));
  const todo = [];
  for (const d of detectors.filter((x) => x.requiresProperty && !configured.has(x.key))) {
    if (!await already(r, 'detector_configuration', 'configKey', `${objectTypeId}:${d.key}`)) todo.push(d);
  }
  if (todo.length === 0 || type.properties.length === 0) return { proposals: [] };

  const result = await r.deps.services.call(callModel, {
    body: {
      role: 'fde', instructions: DETECTOR_INSTRUCTIONS,
      vocabulary: {
        objectTypes: [{
          name: type.apiName, description: type.description ?? undefined,
          properties: type.properties.map((p) => ({ name: p.apiName, type: p.dataType, ...(p.description ? { description: p.description } : {}) })),
        }],
        documentation: todo.map((d) => ({ title: d.key, text: `${d.name}: ${d.description}` })),
      },
      question: `Which properties of ${type.apiName} should each detector examine?`,
      output: outputSpec('detector_fields', DETECTOR_FIELDS), engagementId: r.e.id, taskId: r.task.id,
    },
  }, as(r));
  let parsed: z.infer<typeof DETECTOR_FIELDS>;
  try {
    parsed = parseOutput(DETECTOR_FIELDS, result.output);
  } catch {
    // A draft failing validation is retried within the attempt limit, never repaired (49.6).
    throw new TaskFailure('schema', 'validate', 'the model\'s answer did not match its schema');
  }
  const modelUse: ModelUse = { callId: result.callId, route: result.route, inputTokens: result.usage.inputTokens, outputTokens: result.usage.outputTokens };
  // Metered once the output validates (52.6): advanced compile, against the engagement.
  try {
    await r.deps.services.call(charge, { body: { operation: 'advanced_compile', correlationId: result.callId, engagementId: r.e.id } },
      as(r, { idempotencyKey: `fde.${r.task.id}.${result.callId}` }));
  } catch (error) {
    const code = (error as { code?: string }).code ?? '';
    if (code.startsWith('metering.')) throw new TaskFailure('limit', 'charge', 'the engagement\'s budget refused the charge');
    throw error;
  }

  const byName = new Map(type.properties.map((p) => [p.apiName, p]));
  const proposals: NewProposal[] = [];
  for (const c of parsed.configurations) {
    const detector = todo.find((d) => d.key === c.detector);
    const properties = c.properties.map((name) => byName.get(name));
    // Engine verification: a detector the type needs, properties the type has. What fails is not proposed (51.1).
    if (detector === undefined || properties.some((p) => p === undefined)) continue;
    const ids = properties.map((p) => p!.identityId);
    proposals.push({
      kind: 'detector_configuration',
      payload: { configKey: `${objectTypeId}:${detector.key}`, objectTypeId, detector: detector.key, properties: ids, propertyNames: c.properties, reason: c.reason },
      evidence: [{ type: 'documentation', document: 'detector', detector: detector.key, detail: detector.description },
        ...c.properties.map((name): Evidence => ({ type: 'organisation_statement', property: name, detail: byName.get(name)!.description ?? `${name}, ${byName.get(name)!.dataType}` }))],
      confidence: c.confidence, verification: { detector_requires_property: true, properties_on_type: true, model_call_id: result.callId },
      markings: await markingsOf(r, { objectTypes: [objectTypeId], properties: ids }),
    });
  }
  return { proposals, modelUse };
}

/** Stage 8 (51.10): a foreign key gives the edge and its direction, never its kind or lead time. */
async function proposeEdges(r: RoleContext): Promise<TaskOutcome> {
  await r.deps.services.call(deriveEdges, { body: {} }, as(r));
  const { edges } = await r.deps.services.call(listEdges, { query: { status: 'proposed' } }, as(r));
  const proposals: NewProposal[] = [];
  for (const edge of edges) {
    if (await already(r, 'dependency_edge', 'edgeId', edge.id)) continue;
    proposals.push({
      kind: 'dependency_edge',
      payload: {
        edgeId: edge.id, fromObjectTypeId: edge.fromObjectTypeId, toObjectTypeId: edge.toObjectTypeId, viaLinkTypeId: edge.viaLinkTypeId,
        version: edge.version, source: edge.source, mustSupply: ['kind', 'leadTime'],
      },
      evidence: [{ type: 'foreign_key', link_type_id: edge.viaLinkTypeId, detail: 'a declared link gives the edge and its direction; its kind and lead time are stated by a person' }],
      // Low: the parts that matter are the person's to state, so it is never accepted as it stands.
      confidence: 0.5, verification: { source: edge.source, edge_status: edge.status },
      markings: await markingsOf(r, { objectTypes: [edge.fromObjectTypeId, edge.toObjectTypeId] }),
    });
  }
  return { proposals };
}

