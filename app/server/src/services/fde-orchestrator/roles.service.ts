// The roles' work (spec 49.3, 51): each task calls the services a person would, as its
// role's FDE principal, under the same policy decisions, and turns what it verified into
// proposals with evidence. What it could not verify it does not propose (51.1): a task fails
// with the sub-stage and the error semantic, and the stage stops for that system.
//
// Built in this release:
//   stage 1  Survey: an estate entry per verified connection, for the scope list
//   stage 3  Ontology: derivation per in-scope connection, an object type or link type per decision
//   stage 4  Ontology: a resolution run per resolvable type, a proposal per what it left undecided
//   stage 5  Integration: write enablement per in-scope connection whose manifest declares writes,
//            from its write-verify-undo class run on a test record a person nominated; no run,
//            or a failed one, stops work on that system with the reason, and the connector
//            stays read-only; a physical source is never cycled. Then Action: an "Update" Action type
//            per accepted type over the connections that have earned writes and declare an
//            update, once each one's enablement is decided
