/** Stage 1 (51.3): the estate from verified connections; without one, the stage asks for a list. */
async function surveyEstate(r: RoleContext): Promise<TaskOutcome> {
  const { connections } = await r.deps.services.call(listConnections, { query: { limit: 500 } }, as(r));
  const ready = connections.filter((c) => c.status === 'verified' || c.status === 'active');
  if (ready.length === 0) throw new TaskFailure('not_found', 'survey', 'no verified connection to survey: list the systems in scope');
  // A system whose connector is still being built (a draft or probing connection) is listed too, for stage 2 to finish.
  const building = connections.filter((c) => c.status === 'draft' || c.status === 'probing');
  const proposals: NewProposal[] = [];
  for (const c of [...ready, ...building]) {
    if (await already(r, 'estate_entry', 'connectionId', c.id)) continue;
    const built = c.status === 'verified' || c.status === 'active';
    proposals.push({
      kind: 'estate_entry',
      payload: { connectionId: c.id, name: c.name, connectorId: c.connectorId, status: c.status },
      evidence: [{ type: 'probe', connection_id: c.id, status: c.status,
        detail: built ? `connection ${c.name} is ${c.status}` : `connection ${c.name} is ${c.status}: its connector is being built (stage 2)` }],
      confidence: built ? 0.9 : 0.6, verification: { connection_status: c.status }, markings: await markingsOf(r, { connections: [c.id] }),
    });
  }
  return { proposals };
}

const EVIDENCE_OF: Record<string, string> = { schema: 'probe', naming: 'documentation', declared_fk: 'foreign_key' };

/** Stage 3 (51.5): derivation from the connection's declared structure; links only from declared keys. */
async function deriveObjectTypes(r: RoleContext): Promise<TaskOutcome> {
  const connectionId = String(refs(r.task)['connectionId'] ?? r.task.connectionId);
  const derived = await r.deps.services.call(startDerivation, { body: { connectionId } }, as(r, { idempotencyKey: `fde.${r.task.id}` }));
  if (derived.decisions.length === 0) throw new TaskFailure('not_found', 'derive', 'the connection declares no object to derive a type from');
  const markings = await markingsOf(r, { connections: [connectionId] });
  const proposals: NewProposal[] = [];
  for (const d of derived.decisions) {
    if (d.status !== 'undecided' || await already(r, d.kind, 'decisionId', d.id)) continue;
    proposals.push({
      kind: d.kind,
      payload: { ontologyProposalId: derived.id, decisionId: d.id, apiName: d.apiName, definition: d.definition as never },
      evidence: d.evidence.map((x): Evidence => ({ type: EVIDENCE_OF[x.source] ?? 'documentation', source: x.source, detail: x.detail })),
      confidence: d.confidence, verification: { derivation_proposal_id: derived.id, branch_id: derived.branchId }, markings,
    });
  }
  return { proposals };
}

/** Stage 4 (51.6): exact keys only; what a run leaves is proposed, never fuzzily matched. */
async function proposeResolution(r: RoleContext): Promise<TaskOutcome> {
  const objectTypeId = String(refs(r.task)['objectTypeId']);
  let runId = refs(r.task)['runId'] as string | undefined;
  if (runId === undefined) {
    const run = await r.deps.services.call(startResolutionRun, { body: { objectTypeId, analyse: true } }, as(r, { idempotencyKey: `fde.${r.task.id}` }));
    runId = run.id;
    if (run.status === 'running') return { wait: true, inputRefs: { ...refs(r.task), runId } };
  }
  const run = await r.deps.services.call(getResolutionRun, { params: { runId } }, as(r));
  if (run.status === 'running') return { wait: true, inputRefs: { ...refs(r.task), runId } };
  if (run.status !== 'completed') throw new TaskFailure('upstream', 'resolve', `the resolution run ${run.status}`);
  const markings = await markingsOf(r, { objectTypes: [objectTypeId] });
  const proposals: NewProposal[] = [];
  for (const id of run.proposals) {
    const p = await r.deps.services.call(getResolutionProposal, { params: { proposalId: id } }, as(r));
    if (p.status !== 'open' || await already(r, 'resolution_pair', 'resolutionProposalId', p.id)) continue;
    const body = p.proposal;
    const counts = body.kind === 'normalisation_rule'
      ? { unmatched_before: body.unmatchedBefore, pairs: body.pairs, basis: body.basis }
      : body.kind === 'pair_list' ? { pairs: body.pairs.length } : {};
    proposals.push({
      kind: 'resolution_pair',
      payload: { resolutionProposalId: p.id, resolutionKind: body.kind, objectTypeId, affectedCount: p.affectedCount, ...counts },
      evidence: [{ type: 'value_overlap', run_id: run.id, computed_in: 'engine', ...counts }],
      confidence: body.kind === 'normalisation_rule' ? (body.basis === 'deterministic' ? 0.8 : 0.6) : 0.7,
      verification: { run_id: run.id, objects: run.objects, unkeyed: run.unkeyed }, markings,
    });
  }
  return { proposals };
}

