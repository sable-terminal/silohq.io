/** Markings of what a proposal touches, so its decider must hold them all (49.7, 52.2). */
async function markingsOf(r: Pick<RoleContext, 'deps' | 'e'>, touches: { connections?: string[]; objectTypes?: string[]; properties?: string[] }) {
  return read(r, async (db) => [
    ...(touches.connections?.length ? await resourceMarkingRepo.markingsFor(db, 'connection', touches.connections) : []),
    ...(touches.objectTypes?.length ? await objectTypeMarkingRepo.markingsFor(db, touches.objectTypes) : []),
    ...(touches.properties?.length ? await resourceMarkingRepo.markingsFor(db, 'property', touches.properties) : []),
  ].map((m) => m.markingId));
}

