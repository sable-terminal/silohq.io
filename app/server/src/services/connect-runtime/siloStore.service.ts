// Reading what a Silo holds (spec 66.5): an Import Silo answers through the same path as any
// connector, its manifest's SQL objects read by the SQL engine. The difference is where the
// statement runs: not in a customer database through the Silo Agent, but in the Silo's own
// store, the cell's siloes project, with the cell's own credentials. A Silo holds a copy, so
// it is only ever read.
//
// The statement is the SQL engine's, generated and parameterised like any other; every job
// is labelled with the organisation, the Silo and its purpose, so BigQuery metering
// attributes the bytes to the Silo (69.7, 74.1). Values are record values in flight: never
// logged, never in an error.

import type { BigQueryAdapter } from '../../infra/bigquery.infra.ts';
import { AppError, isAppError } from '../../utils/errors.util.ts';

export interface SiloStoreQuery {
  organisationId: string;
  connectionId: string;
  /** The Silo the manifest's transport names, and its dataset (the source's schema). */
  siloId: string;
  dataset: string;
  /** Generated by the SQL engine in the store's grammar: text with @p1..@pn, and the bound values in order. */
  statement: { text: string; values: unknown[] };
  maxRows: number;
  signal: AbortSignal;
}

export interface SiloStoreChannel {
  query(input: SiloStoreQuery): Promise<{ rows: Record<string, unknown>[] }>;
}

/** A cell with no Silo store (the sovereign build has no BigQuery, 6.5): a Silo source is unreachable. */
export const NO_SILO_STORE: SiloStoreChannel = {
  async query() {
    throw new AppError('unavailable', 'this cell holds no Silo store', { code: 'connection.silo_store_unavailable', retryable: false });
  },
};

/** The cell's siloes project, read through the BigQuery adapter. */
export function createSiloStore(bigQuery: BigQueryAdapter, projectId: string): SiloStoreChannel {
  return {
    async query(input) {
      if (input.signal.aborted) throw new AppError('unavailable', 'the read was cancelled', { code: 'connection.read_cancelled' });
      try {
        const outcome = await bigQuery.run({ projectId, dataset: input.dataset }, { text: input.statement.text, values: input.statement.values }, {
          labels: { organisation: input.organisationId, service: 'connect-runtime', purpose: 'silo_query', silo: input.siloId },
        });
        return { rows: outcome.rows.slice(0, input.maxRows + 1) };
      } catch (error) {
        if (isAppError(error)) throw error;
        throw new AppError('upstream', 'the Silo store did not answer', { code: 'connection.silo_store_failed' });
      }
    },
  };
}
