export interface AgentChannel {
  query(input: AgentQuery): Promise<AgentRows>;
  /** MQTT reads; absent on a channel without the plugin. */
  mqtt?(input: AgentMqttSnapshot): Promise<{ messages: AgentMqttMessage[]; truncated: boolean }>;
  /** OPC UA reads; absent on a channel without the plugin. */
  opcua?(input: AgentOpcUaRead): Promise<{ rows: Record<string, unknown>[]; truncated: boolean }>;
  /** OPC UA: connect and report the server's namespaces and certificate (the endpoint's verification). */
  opcuaProbe?(input: AgentOpcUaServer): Promise<AgentOpcUaProbe>;
  /** OPC UA setpoint writes, on their grant, checked by the agent against its signed allow-list (47.4). */
  opcuaWrite?(input: AgentOpcUaServer & {
    root: string; typeDefinition?: string | undefined; statements: AgentPhysicalStatement[]; grant?: SignedExecutionGrant | undefined;
  }): Promise<AgentPhysicalResult[]>;
  /** OPC UA method calls (commands), on their grant, checked by the agent against its signed allow-list (47.4). */
  opcuaCall?(input: AgentOpcUaServer & {
    root: string; typeDefinition?: string | undefined; statements: AgentCallStatement[]; grant?: SignedExecutionGrant | undefined;
  }): Promise<AgentPhysicalResult[]>;
  /** MQTT command publishes, on their grant, checked by the agent against its signed allow-list (47.4). */
  mqttPublish?(input: AgentMqttPublish): Promise<AgentPhysicalResult[]>;
  /** Writes; absent on a channel that only reads. */
  transaction?(input: AgentTransaction): Promise<AgentTransactionResult>;
  /** Outbound webhooks to private targets; absent on a channel without them. */
  http?(input: AgentHttp): Promise<AgentHttpResult>;
  /** A file share on the agent's host; absent on a channel without it. */
  files?(input: AgentFiles): Promise<AgentFilesResult>;
  /** SFTP through the agent; absent on a channel without it. */
  sftp?(input: AgentSftp): Promise<AgentFilesResult>;
}

/** The channel for one request: every read and write through it names who asks and why. */
export function withLogin(channel: AgentChannel, login: AgentLogin): AgentChannel {
  // The agent channel's read, not a database client's (tests/architecture/sql.test.ts looks for those).
  const read = channel.query.bind(channel);
  const write = channel.transaction?.bind(channel);
  const mqtt = channel.mqtt?.bind(channel);
  const opcua = channel.opcua?.bind(channel);
  const opcuaProbe = channel.opcuaProbe?.bind(channel);
  const opcuaWrite = channel.opcuaWrite?.bind(channel);
  const opcuaCall = channel.opcuaCall?.bind(channel);
  const mqttPublish = channel.mqttPublish?.bind(channel);
  // A file share carries no login: the host's own permissions and its owner's roots decide.
  const files = channel.files?.bind(channel);
  const sftp = channel.sftp?.bind(channel);
  return {
    query: (input) => read({ ...input, login }),
    ...(opcua === undefined ? {} : { opcua: (input: AgentOpcUaRead) => opcua({ ...input, login }) }),
    ...(opcuaProbe === undefined ? {} : { opcuaProbe: (input: AgentOpcUaServer) => opcuaProbe({ ...input, login }) }),
    ...(opcuaWrite === undefined ? {} : { opcuaWrite: (input: Parameters<NonNullable<AgentChannel['opcuaWrite']>>[0]) => opcuaWrite({ ...input, login }) }),
    ...(opcuaCall === undefined ? {} : { opcuaCall: (input: Parameters<NonNullable<AgentChannel['opcuaCall']>>[0]) => opcuaCall({ ...input, login }) }),
    ...(mqtt === undefined ? {} : { mqtt: (input: AgentMqttSnapshot) => mqtt({ ...input, login }) }),
    ...(mqttPublish === undefined ? {} : { mqttPublish: (input: AgentMqttPublish) => mqttPublish({ ...input, login }) }),
    ...(files === undefined ? {} : { files }),
    ...(sftp === undefined ? {} : { sftp: (input: AgentSftp) => sftp({ ...input, login }) }),
    ...(write === undefined ? {} : { transaction: (input: AgentTransaction) => write({ ...input, login }) }),
    ...(channel.http === undefined ? {} : { http: channel.http.bind(channel) }),
  };
}

/**
 * The SQL engine's channel through the tunnels this replica holds: a read is given to the
 * pool's least-loaded healthy agent and its rows collected; a transaction's row counts come
 * back with its done. The agent's refusal keeps its SQLSTATE and nothing else.
 */
/** An industrial server's refusal, by the reason the agent gives (20.2, 20.3). */
function industrialRefusal(frame: Extract<ResultFrame, { type: 'error' }>): AppError | undefined {
  switch (frame.reason) {
    case 'login':
      return new AppError('unauthenticated', 'the server refused the connection\'s login', { code: 'source.login_refused' });
    case 'untrusted':
      return new AppError('forbidden', 'the server does not trust the endpoint\'s application certificate: trust it on the server, then verify the endpoint', {
        code: 'industrial.endpoint_untrusted',
      });
    case 'server_certificate':
      return new AppError('forbidden', 'the server presented a certificate other than the one pinned for the endpoint; nothing was sent to it', {
        code: 'industrial.server_certificate_mismatch',
      });
    case 'policy':
      return new AppError('conflict', 'the server offers no endpoint with this security policy and mode', { code: 'industrial.policy_not_offered' });
    default:
      return undefined;
  }
}

/** Why an application key is opened, by why the login is: reads serving a person need a live connection; building and probing do not. */
const KEY_REASONS = {
  query: 'query', mutation: 'query', read_back: 'query', change_stream: 'change_stream', connect: 'probe', probe: 'probe',
} as const satisfies Record<AgentLogin['reason'], 'query' | 'probe' | 'change_stream'>;

/** The payload and key sealing an OPC UA server's work carries. */
function opcuaServer(input: AgentOpcUaServer) {
  return {
    payload: {
      connectionId: input.connectionId, endpointUrl: input.endpointUrl, securityPolicy: input.securityPolicy,
      ...(input.signed === undefined ? {} : { certificate: input.signed.certificate, serverThumbprint: input.signed.serverThumbprint }),
    },
    ...(input.login === undefined || !input.sealLogin ? {} : { seal: { connectionId: input.connectionId, ...input.login } }),
    ...(input.signed === undefined || input.login === undefined ? {} : {
      sealKey: {
        connectionId: input.connectionId, endpointId: input.signed.endpointId, reason: KEY_REASONS[input.login.reason],
        request: input.login.request, correlationId: input.login.correlationId,
      },
    }),
  };
}

export function tunnelChannel(tunnels: AgentTunnels): AgentChannel {
  const refusal = (frame: Extract<ResultFrame, { type: 'error' }>): Error => {
    if (frame.category === 'source_refused') return new SourceSqlError(frame.sqlstate ?? 'XX000');
    if (frame.category === 'row_count_mismatch') return new RowCountMismatch(frame.index ?? 0, frame.rows ?? 0);
    if (frame.category === 'timeout') return new AppError('timeout', 'the source did not answer in time', { code: 'agent.source_timeout' });
    if (frame.category === 'bounds') return new AppError('bounds', 'the answer was larger than the agent may return', { code: 'agent.bounds' });
    if (frame.category === 'login_refused') {
      const reason = frame.reason ?? 'sealing';
      return new AppError(reason === 'target' ? 'forbidden' : 'source_unreachable', reason === 'target'
        ? 'the agent\'s host does not let it reach this connection\'s system: its owner adds it to targets in the agent\'s configuration'
        : 'the agent did not take the connection\'s login', { code: 'agent.login_refused', details: { reason } });
    }
    if (frame.category === 'target_refused') {
      return new AppError('forbidden', 'the agent\'s host does not let it reach this address: its owner adds it to targets in the agent\'s configuration', {
        code: 'agent.target_refused',
      });
    }
    if (frame.category === 'actuation_refused') {
      return new AppError('forbidden', 'the agent refused the physical write: its signed allow-list does not let it be sent now', {
        code: 'actuation.refused_by_agent', details: { reason: frame.reason ?? 'not_listed' },
      });
    }
    if (frame.category === 'grant_refused') {
      return new AppError('forbidden', 'the agent refused the write: its execution grant does not hold', {
        code: 'agent.write_grant_refused', details: { reason: frame.reason ?? 'unsigned' },
      });
    }
    return new AppError('source_unreachable', 'the agent could not reach the source', { code: `agent.${frame.category}` });
  };
  /** A physical write's or command's rows (47.4): one per statement, then done; a refusal of the whole as the server's or the agent's. */
  async function physicalResults(frames: AsyncIterable<ResultFrame>, refused: string): Promise<AgentPhysicalResult[]> {
    const results: AgentPhysicalResult[] = [];
    for await (const frame of frames) {
      if (frame.type === 'rows') results.push(...(frame.rows as unknown as AgentPhysicalResult[]));
      if (frame.type === 'error') {
        if (frame.category === 'source_refused') throw industrialRefusal(frame) ?? new AppError('source_unreachable', refused, { code: 'source.refused' });
        throw refusal(frame);
      }
      if (frame.type === 'done') return results;
    }
    throw new AppError('source_unreachable', 'the agent ended without an answer', { code: 'agent.answer_broken' });
  }

  /** A listing, or a file in its chunks in order, from the agent's frames; a refusal as the source's or the agent's. */
  async function fileFrames(frames: AsyncIterable<ResultFrame>, op: AgentFiles['operation'], refusedTarget: string): Promise<AgentFilesResult> {
    const rows: Record<string, unknown>[] = [];
    for await (const frame of frames) {
      if (frame.type === 'rows') rows.push(...frame.rows);
      if (frame.type === 'error') {
        if (frame.category === 'source_refused') {
          const reason = frame.reason ?? 'refused';
          throw reason === 'not_found' ? new AppError('not_found', 'the server or share has no such directory or file', { code: 'files.not_found' })
            : reason === 'untrusted' ? new AppError('forbidden', 'the server presented a host key other than the one the connection pins', { code: 'sftp.host_key_mismatch' })
              : reason === 'login' ? new AppError('unauthenticated', 'the server refused the connection\'s login', { code: 'source.auth' })
                : new AppError('source_unreachable', 'the source refused the read', { code: `files.${reason}` });
        }
        if (frame.category === 'target_refused') throw new AppError('forbidden', refusedTarget, { code: 'agent.target_refused' });
        throw refusal(frame);
      }
      if (frame.type === 'done') {
        if (op.kind === 'list') {
          return { kind: 'list', entries: rows.map((r) => ({ name: String(r['name']), size: Number(r['size']), modifiedAt: String(r['modifiedAt']) })) };
        }
        // The file's chunks, in order: each names its offset, so a gap or overlap is caught, never stitched.
        const chunks: Buffer[] = [];
        let at = 0;
        for (const r of rows) {
          if (Number(r['offset']) !== at) throw new AppError('integrity', 'the agent sent the file out of order', { code: 'agent.answer_broken' });
          const chunk = Buffer.from(String(r['data']), 'base64');
          chunks.push(chunk);
          at += chunk.length;
          if (at > op.maxBytes) throw new AppError('bounds', `${op.name} is larger than ${op.maxBytes} bytes`, { code: 'sftp.file_too_large', details: { bound: 'max_file_bytes', limit: op.maxBytes } });
        }
        return { kind: 'read', size: at, contentBase64: Buffer.concat(chunks).toString('base64') };
      }
    }
    throw new AppError('source_unreachable', 'the agent ended without an answer', { code: 'agent.answer_broken' });
  }

  return {
    async query(input) {
      const rows: Record<string, unknown>[] = [];
      for await (const frame of tunnels.dispatch({
        organisationId: input.organisationId, poolId: input.agentPoolId, kind: 'sql.read', timeoutMs: input.timeoutMs, signal: input.signal,
        payload: { connectionId: input.connectionId, dialect: input.dialect, statement: input.statement, maxRows: input.maxRows },
        ...(input.login === undefined ? {} : { seal: { connectionId: input.connectionId, ...input.login } }),
      })) {
        if (frame.type === 'rows') rows.push(...frame.rows);
        if (frame.type === 'error') throw refusal(frame);
      }
      return { rows };
    },
    async transaction(input) {
      for await (const frame of tunnels.dispatch({
        organisationId: input.organisationId, poolId: input.agentPoolId, kind: 'sql.transaction', timeoutMs: input.timeoutMs, signal: input.signal,
        payload: { connectionId: input.connectionId, dialect: input.dialect, statements: input.statements, ...(input.grant === undefined ? {} : { grant: input.grant }) },
        ...(input.login === undefined ? {} : { seal: { connectionId: input.connectionId, ...input.login } }),
      })) {
        if (frame.type === 'error') throw refusal(frame);
        if (frame.type === 'done') return { rowCounts: frame.rowCounts ?? [] };
      }
      throw new AppError('source_unreachable', 'the agent ended without an answer', { code: 'agent.answer_broken' });
    },
    async mqtt(input) {
      const messages: AgentMqttMessage[] = [];
      let truncated = false;
      for await (const frame of tunnels.dispatch({
        organisationId: input.organisationId, poolId: input.agentPoolId, kind: 'mqtt.snapshot', timeoutMs: input.timeoutMs, signal: input.signal,
        payload: { connectionId: input.connectionId, endpointUrl: input.endpointUrl, topics: input.topics, windowMs: input.windowMs, maxMessages: input.maxMessages },
        ...(input.login === undefined || !input.sealLogin ? {} : { seal: { connectionId: input.connectionId, ...input.login } }),
      })) {
        if (frame.type === 'rows') messages.push(...(frame.rows as unknown as AgentMqttMessage[]));
        if (frame.type === 'done') truncated = frame.truncated;
        if (frame.type === 'error') {
          if (frame.category === 'source_refused') {
            throw industrialRefusal(frame) ?? new AppError('unauthenticated', 'the broker refused the connection\'s login or subscription', { code: 'source.auth' });
          }
          throw refusal(frame);
        }
      }
      return { messages, truncated };
    },
    async opcua(input) {
      const rows: Record<string, unknown>[] = [];
      let truncated = false;
      const server = opcuaServer(input);
      for await (const frame of tunnels.dispatch({
        organisationId: input.organisationId, poolId: input.agentPoolId, kind: 'opcua.read', timeoutMs: input.timeoutMs, signal: input.signal,
        ...server,
        payload: {
          ...server.payload, root: input.root,
          ...(input.typeDefinition === undefined ? {} : { typeDefinition: input.typeDefinition }), paths: input.paths, maxInstances: input.maxInstances,
        },
      })) {
        if (frame.type === 'rows') rows.push(...frame.rows);
        if (frame.type === 'done') truncated = frame.truncated;
        if (frame.type === 'error') {
          if (frame.category === 'source_refused') {
            throw industrialRefusal(frame)
              ?? new AppError('not_found', 'the server refused the read: the root node or its namespace is not as the manifest says', { code: 'source.not_found' });
          }
          throw refusal(frame);
        }
      }
      return { rows, truncated };
    },
    async opcuaWrite(input) {
      const server = opcuaServer(input);
      return physicalResults(tunnels.dispatch({
        organisationId: input.organisationId, poolId: input.agentPoolId, kind: 'opcua.write', timeoutMs: input.timeoutMs, signal: input.signal,
        ...server,
        payload: {
          ...server.payload, root: input.root, ...(input.typeDefinition === undefined ? {} : { typeDefinition: input.typeDefinition }),
          statements: input.statements, ...(input.grant === undefined ? {} : { grant: input.grant }),
        },
      }), 'the server refused the connection');
    },
    async opcuaCall(input) {
      const server = opcuaServer(input);
      return physicalResults(tunnels.dispatch({
        organisationId: input.organisationId, poolId: input.agentPoolId, kind: 'opcua.call', timeoutMs: input.timeoutMs, signal: input.signal,
        ...server,
        payload: {
          ...server.payload, root: input.root, ...(input.typeDefinition === undefined ? {} : { typeDefinition: input.typeDefinition }),
          statements: input.statements, ...(input.grant === undefined ? {} : { grant: input.grant }),
        },
      }), 'the server refused the connection');
    },
    async mqttPublish(input) {
      return physicalResults(tunnels.dispatch({
        organisationId: input.organisationId, poolId: input.agentPoolId, kind: 'mqtt.publish', timeoutMs: input.timeoutMs, signal: input.signal,
        payload: { connectionId: input.connectionId, endpointUrl: input.endpointUrl, statements: input.statements, ...(input.grant === undefined ? {} : { grant: input.grant }) },
        ...(input.login === undefined || !input.sealLogin ? {} : { seal: { connectionId: input.connectionId, ...input.login } }),
      }), 'the broker refused the connection or its login');
    },
    async opcuaProbe(input) {
      let found: AgentOpcUaProbe | undefined;
      for await (const frame of tunnels.dispatch({
        organisationId: input.organisationId, poolId: input.agentPoolId, kind: 'opcua.probe', timeoutMs: input.timeoutMs, signal: input.signal,
        ...opcuaServer(input),
      })) {
        if (frame.type === 'rows' && frame.rows[0] !== undefined) {
          const row = frame.rows[0];
          found = {
            namespaceUris: Array.isArray(row['namespaceUris']) ? row['namespaceUris'].filter((u): u is string => typeof u === 'string').slice(0, 1_000) : [],
            ...(typeof row['serverSha1'] === 'string' ? { serverSha1: row['serverSha1'] } : {}),
            ...(typeof row['serverSha256'] === 'string' ? { serverSha256: row['serverSha256'] } : {}),
          };
        }
        if (frame.type === 'error') {
          if (frame.category === 'source_refused') {
            throw industrialRefusal(frame) ?? new AppError('source_unreachable', 'the server refused the connection', { code: 'source.refused' });
          }
          throw refusal(frame);
        }
        if (frame.type === 'done' && found !== undefined) return found;
      }
      throw new AppError('source_unreachable', 'the agent ended without an answer', { code: 'agent.answer_broken' });
    },
    async http(input) {
      for await (const frame of tunnels.dispatch({
        organisationId: input.organisationId, poolId: input.agentPoolId, kind: 'http.send', timeoutMs: input.timeoutMs, signal: input.signal,
        payload: { connectionId: input.connectionId, statements: input.statements, ...(input.grant === undefined ? {} : { grant: input.grant }) },
      })) {
        if (frame.type === 'error') throw refusal(frame);
        if (frame.type === 'http_result') return { status: frame.status, state: frame.state ?? null };
      }
      throw new AppError('source_unreachable', 'the agent ended without an answer', { code: 'agent.answer_broken' });
    },
    async files(input) {
      const op = input.operation;
      return fileFrames(tunnels.dispatch({
        organisationId: input.organisationId, poolId: input.agentPoolId, kind: op.kind === 'list' ? 'files.list' : 'files.read', timeoutMs: input.timeoutMs, signal: input.signal,
        payload: { connectionId: input.connectionId, root: input.root, directory: op.directory, ...(op.kind === 'read' ? { name: op.name, maxBytes: op.maxBytes } : {}) },
      }), op, 'the agent\'s host does not let it read this path: its owner adds the share to fileRoots in the agent\'s configuration');
    },
    async sftp(input) {
      const op = input.operation;
      return fileFrames(tunnels.dispatch({
        organisationId: input.organisationId, poolId: input.agentPoolId, kind: op.kind === 'list' ? 'sftp.list' : 'sftp.read', timeoutMs: input.timeoutMs, signal: input.signal,
        payload: {
          connectionId: input.connectionId, host: input.host, port: input.port, basePath: input.basePath, hostKeySha256: input.hostKeySha256,
          directory: op.directory, ...(op.kind === 'read' ? { name: op.name, maxBytes: op.maxBytes } : {}),
        },
        ...(input.login === undefined ? {} : { seal: { connectionId: input.connectionId, ...input.login } }),
      }), op, 'the agent\'s host does not let it reach this server: its owner adds it to targets in the agent\'s configuration');
    },
  };
}

